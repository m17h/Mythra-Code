//! Normal-browser selection only. No shell command strings or webview loading.
use serde_json::{json, Value};

fn compatible(id: &str) -> bool {
    let id = id.to_ascii_lowercase();
    [
        "com.google.chrome",
        "org.chromium.chromium",
        "com.microsoft.edgemac",
        "com.brave.browser",
        "company.thebrowser.browser",
        "com.vivaldi.vivaldi",
        "com.operasoftware.opera",
        "org.mozilla.firefox",
        "org.mozilla.nightly",
        "app.zen-browser.zen",
        "io.gitlab.librewolf-community",
        "org.waterfoxproject.waterfox",
        "one.ablaze.floorp",
    ]
    .iter()
    .any(|prefix| id.starts_with(prefix))
}
fn unavailable() -> Value {
    json!({"opened":false,"reason":"This preview needs a Chromium or Firefox browser because Safari cannot resolve its isolated localhost address. Install a compatible browser, then open this URL there."})
}
/// URL is generated by the gateway, never caller-supplied. No browser discovery
/// or launches happen at startup; only the explicit preview-open command calls us.
pub(super) fn open(url: &str) -> Value {
    let Ok(parsed) = reqwest::Url::parse(url) else {
        return unavailable();
    };
    if parsed.scheme() != "http"
        || !parsed
            .host_str()
            .is_some_and(|h| h.starts_with("p-") && h.ends_with(".localhost"))
        || parsed.port().is_none()
    {
        return unavailable();
    }
    platform(url)
}
#[cfg(target_os = "macos")]
fn platform(url: &str) -> Value {
    use std::ffi::{c_char, c_void};
    type Cf = *const c_void;
    #[link(name = "CoreFoundation", kind = "framework")]
    extern "C" {
        fn CFStringCreateWithBytes(
            allocator: Cf,
            bytes: *const u8,
            length: isize,
            encoding: u32,
            external: u8,
        ) -> Cf;
        fn CFStringGetCString(string: Cf, buffer: *mut c_char, size: isize, encoding: u32) -> u8;
        fn CFArrayGetCount(array: Cf) -> isize;
        fn CFRelease(value: Cf);
    }
    #[link(name = "CoreServices", kind = "framework")]
    extern "C" {
        fn LSCopyDefaultHandlerForURLScheme(scheme: Cf) -> Cf;
        fn LSCopyApplicationURLsForBundleIdentifier(id: Cf, error: *mut Cf) -> Cf;
    }
    struct Owned(Cf);
    impl Drop for Owned {
        fn drop(&mut self) {
            if !self.0.is_null() {
                unsafe { CFRelease(self.0) }
            }
        }
    }
    fn cf(value: &str) -> Owned {
        Owned(unsafe {
            CFStringCreateWithBytes(
                std::ptr::null(),
                value.as_ptr(),
                value.len() as isize,
                0x08000100,
                0,
            )
        })
    }
    let scheme = cf("http");
    if scheme.0.is_null() {
        return unavailable();
    }
    let default = Owned(unsafe { LSCopyDefaultHandlerForURLScheme(scheme.0) });
    let mut candidates = Vec::new();
    if !default.0.is_null() {
        let mut bytes = [0u8; 1024];
        if unsafe {
            CFStringGetCString(
                default.0,
                bytes.as_mut_ptr().cast(),
                bytes.len() as isize,
                0x08000100,
            )
        } != 0
        {
            if let Some(end) = bytes.iter().position(|b| *b == 0) {
                if let Ok(id) = std::str::from_utf8(&bytes[..end]) {
                    if compatible(id) {
                        candidates.push(id.to_owned());
                    }
                }
            }
        }
    }
    for id in [
        "com.google.Chrome",
        "org.mozilla.firefox",
        "com.microsoft.edgemac",
        "com.brave.Browser",
        "org.chromium.Chromium",
        "company.thebrowser.Browser",
        "com.vivaldi.Vivaldi",
        "com.operasoftware.Opera",
        "com.google.Chrome.canary",
        "org.mozilla.nightly",
    ] {
        if !candidates.iter().any(|c| c == id) {
            candidates.push(id.into());
        }
    }
    for id in candidates {
        let bundle = cf(&id);
        if bundle.0.is_null() {
            continue;
        }
        // Copy-rule objects are released after use; no borrowed array element
        // escapes its owner. A null error pointer requests no error allocation.
        let installed = Owned(unsafe {
            LSCopyApplicationURLsForBundleIdentifier(bundle.0, std::ptr::null_mut())
        });
        if installed.0.is_null() || unsafe { CFArrayGetCount(installed.0) } <= 0 {
            continue;
        }
        if launch(std::process::Command::new("/usr/bin/open").args(["-b", &id, "--", url])) {
            return json!({"opened":true,"browser":id});
        }
    }
    unavailable()
}
#[cfg(windows)]
fn platform(url: &str) -> Value {
    use std::{ffi::c_void, path::PathBuf};
    #[link(name = "advapi32")]
    extern "system" {
        fn RegGetValueW(
            key: *mut c_void,
            subkey: *const u16,
            name: *const u16,
            flags: u32,
            kind: *mut u32,
            data: *mut c_void,
            bytes: *mut u32,
        ) -> i32;
    }
    fn read(key: usize, subkey: &str, name: Option<&str>, view: u32) -> Option<String> {
        let sub: Vec<_> = subkey.encode_utf16().chain(Some(0)).collect();
        let name = name.map(|n| n.encode_utf16().chain(Some(0)).collect::<Vec<_>>());
        let mut buffer = vec![0u16; 32768];
        let mut bytes = (buffer.len() * 2) as u32;
        let mut kind = 0;
        let rc = unsafe {
            RegGetValueW(
                key as isize as *mut c_void,
                sub.as_ptr(),
                name.as_ref().map_or(std::ptr::null(), |n| n.as_ptr()),
                2 | view,
                &mut kind,
                buffer.as_mut_ptr().cast(),
                &mut bytes,
            )
        };
        if rc != 0 || kind != 1 || bytes < 2 || bytes as usize > buffer.len() * 2 || bytes % 2 != 0
        {
            return None;
        }
        buffer.truncate(bytes as usize / 2);
        if buffer.pop() != Some(0) || buffer.contains(&0) {
            return None;
        }
        String::from_utf16(&buffer).ok()
    }
    // Pseudo-handles must be sign-extended on 64-bit Windows.
    let hkcu = 0x80000001u32 as i32 as isize as usize;
    let hklm = 0x80000002u32 as i32 as isize as usize;
    let default = read(
        hkcu,
        r"Software\Microsoft\Windows\Shell\Associations\UrlAssociations\http\UserChoice",
        Some("ProgId"),
        0,
    )
    .unwrap_or_default()
    .to_ascii_lowercase();
    if ["chrome", "firefox", "msedge", "brave", "vivaldi", "opera"]
        .iter()
        .any(|family| default.starts_with(family))
    {
        use windows::Win32::System::Com::{
            CoInitializeEx, CoUninitialize, COINIT_APARTMENTTHREADED,
        };
        struct Com(bool);
        impl Drop for Com {
            fn drop(&mut self) {
                if self.0 {
                    unsafe { CoUninitialize() }
                }
            }
        }
        // ShellExecute may delegate to COM shell handlers. Balance only our
        // successful initialization; never uninitialize another apartment.
        let _com = Com(unsafe { CoInitializeEx(None, COINIT_APARTMENTTHREADED) }.is_ok());
        #[link(name = "shell32")]
        extern "system" {
            fn ShellExecuteW(
                window: *mut c_void,
                operation: *const u16,
                file: *const u16,
                parameters: *const u16,
                directory: *const u16,
                show: i32,
            ) -> *mut c_void;
        }
        let action: Vec<_> = "open".encode_utf16().chain(Some(0)).collect();
        let target: Vec<_> = url.encode_utf16().chain(Some(0)).collect();
        if unsafe {
            ShellExecuteW(
                std::ptr::null_mut(),
                action.as_ptr(),
                target.as_ptr(),
                std::ptr::null(),
                std::ptr::null(),
                1,
            )
        } as isize
            > 32
        {
            return json!({"opened":true,"browser":"default"});
        }
    }
    let mut browsers = vec![
        ("chrome.exe", "chrome"),
        ("firefox.exe", "firefox"),
        ("msedge.exe", "msedge"),
        ("brave.exe", "brave"),
        ("vivaldi.exe", "vivaldi"),
        ("opera.exe", "opera"),
    ];
    browsers.sort_by_key(|(_, family)| !default.starts_with(family));
    for (exe, _) in browsers {
        for key in [hkcu, hklm] {
            for view in [0x10000, 0x20000] {
                let sub = format!(r"Software\Microsoft\Windows\CurrentVersion\App Paths\{exe}");
                let Some(path) = read(key, &sub, None, view).map(PathBuf::from) else {
                    continue;
                };
                if !path.is_absolute()
                    || !path.is_file()
                    || !path
                        .file_name()
                        .is_some_and(|f| f.to_string_lossy().eq_ignore_ascii_case(exe))
                {
                    continue;
                }
                if launch(std::process::Command::new(&path).arg(url)) {
                    return json!({"opened":true,"browser":exe});
                }
            }
        }
    }
    unavailable()
}
#[cfg(not(any(target_os = "macos", windows)))]
fn platform(_url: &str) -> Value {
    unavailable()
}
fn launch(command: &mut std::process::Command) -> bool {
    use std::{
        process::Stdio,
        time::{Duration, Instant},
    };
    let Ok(mut child) = command
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
    else {
        return false;
    };
    // Browser launchers normally exit immediately when handing to an existing
    // instance. Do not wait for the GUI lifetime or leave a zombie child.
    let deadline = Instant::now() + Duration::from_millis(500);
    loop {
        match child.try_wait() {
            Ok(Some(status)) => return status.success(),
            Err(_) => return false,
            Ok(None) => {
                if Instant::now() >= deadline {
                    std::thread::spawn(move || {
                        let _ = child.wait();
                    });
                    return true;
                }
                std::thread::sleep(Duration::from_millis(20));
            }
        }
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn browser_family_policy_does_not_open_safari_or_unknown_handlers() {
        for id in [
            "com.apple.Safari",
            "com.apple.SafariTechnologyPreview",
            "com.example.Unknown",
        ] {
            assert!(!super::compatible(id));
        }
        for id in [
            "com.google.Chrome",
            "com.google.Chrome.canary",
            "org.mozilla.firefox",
            "org.mozilla.nightly",
            "com.microsoft.edgemac",
            "com.brave.Browser",
        ] {
            assert!(super::compatible(id));
        }
    }
}
